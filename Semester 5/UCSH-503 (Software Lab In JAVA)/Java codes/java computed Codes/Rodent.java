public class Rodent
{
    public void display()
    {
        System.out.println("Rodents are small mammals with sharp teeth.");
    }

    public void move()
    {
        int i = 0;
        while (i < 1)
        {
            System.out.println("Rodents scurry quickly.");
            i = i + 1;
        }
    }
}
